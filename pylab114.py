
# Demonstration of Operator Precedence and Associativity

# Operator Precedence
a = 10 + 5 * 2
print("Operator Precedence:", a)

b = (10 + 5) * 2
print("Using Parentheses:", b)

# Operator Associativity
c = 20 - 5 - 3
print("Left to Right Associativity:", c)

d = 2 ** 3 ** 2
print("Right to Left Associativity:", d)
