
# Demonstration of Type Conversion

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
x = 12.5
y = int(x)
print("Float to Integer:", y)

# Integer to String
num = 100
s = str(num)
print("Integer to String:", s)

# String to Integer
text = "50"
n = int(text)
print("String to Integer:", n)

# String to Float
value = "25.5"
f = float(value)
print("String to Float:", f)
